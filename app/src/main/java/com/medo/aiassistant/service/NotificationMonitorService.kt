package com.medo.aiassistant.service

import android.app.Notification
import android.content.pm.PackageManager
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.util.Log
import com.medo.aiassistant.MedoApplication
import com.medo.aiassistant.data.NotificationEntity
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch

class NotificationMonitorService : NotificationListenerService() {

    private val serviceScope = CoroutineScope(Dispatchers.IO)
    private val TAG = "NotificationMonitor"

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        super.onNotificationPosted(sbn)
        if (sbn == null) return

        // 1. Ignore ongoing notifications (music players, download bars, foreground status)
        if (sbn.isOngoing) {
            return
        }

        val packageName = sbn.packageName ?: return

        // 2. Ignore notifications generated by this app itself
        if (packageName == applicationContext.packageName) {
            return
        }

        // 3. Extract notification extras
        val extras = sbn.notification.extras ?: return
        val titleCharSequence = extras.getCharSequence(Notification.EXTRA_TITLE)
        val textCharSequence = extras.getCharSequence(Notification.EXTRA_BIG_TEXT)
            ?: extras.getCharSequence(Notification.EXTRA_TEXT)

        val title = titleCharSequence?.toString()?.trim() ?: ""
        val content = textCharSequence?.toString()?.trim() ?: ""

        // 4. Ignore notifications with no meaningful text
        if (title.isEmpty() && content.isEmpty()) {
            return
        }

        // 5. Get friendly app name
        val appName = try {
            val pm = applicationContext.packageManager
            val appInfo = pm.getApplicationInfo(packageName, 0)
            pm.getApplicationLabel(appInfo).toString()
        } catch (e: PackageManager.NameNotFoundException) {
            packageName
        }

        val timestamp = sbn.postTime.takeIf { it > 0 } ?: System.currentTimeMillis()

        Log.d(TAG, "Captured notification from $appName: $title -> $content")

        // 6. Save to local database
        serviceScope.launch {
            try {
                val entity = NotificationEntity(
                    packageName = packageName,
                    appName = appName,
                    title = title,
                    content = content,
                    timestamp = timestamp
                )
                val db = (application as? MedoApplication)?.database
                db?.notificationDao()?.insert(entity)
            } catch (e: Exception) {
                Log.e(TAG, "Error saving notification", e)
            }
        }
    }

    override fun onListenerConnected() {
        super.onListenerConnected()
        Log.i(TAG, "NotificationListenerService connected successfully!")
    }

    override fun onListenerDisconnected() {
        super.onListenerDisconnected()
        Log.w(TAG, "NotificationListenerService disconnected.")
    }
}
